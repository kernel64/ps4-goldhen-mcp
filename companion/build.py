"""Build companion/agent.c into the flat binary the PC injects, and embed it in the package.

    uv run python companion/build.py            # needs clang + ld.lld (LLVM 18), see PS4_LLVM_BIN

Writes src/ps4_goldhen_mcp/_agent_blob.py (base64 + SHA-256) and companion/build/agent.bin for
tests/test_agent_blob.py. The link keeps its relocations (--emit-relocs) so the result can be checked
to be position independent: PC-relative relocations only, no .data/.bss, agent_main at offset 0.
"""

from __future__ import annotations

import base64
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile
from elftools.elf.relocation import RelocationSection

HERE = Path(__file__).resolve().parent
OUT = HERE / "build"
BLOB_PY = HERE.parent / "src" / "ps4_goldhen_mcp" / "_agent_blob.py"
PC_RELATIVE = {"R_X86_64_PC32", "R_X86_64_PLT32", "R_X86_64_PC64", "R_X86_64_NONE"}
RELOC_NAMES = {0: "R_X86_64_NONE", 1: "R_X86_64_64", 2: "R_X86_64_PC32", 4: "R_X86_64_PLT32", 9: "R_X86_64_GOTPCREL",
               10: "R_X86_64_32", 11: "R_X86_64_32S", 24: "R_X86_64_PC64", 41: "R_X86_64_GOTPCRELX",
               42: "R_X86_64_REX_GOTPCRELX"}


def tool(name: str) -> str:
    d = os.environ.get("PS4_LLVM_BIN")
    if p := shutil.which(name, path=d) if d else shutil.which(name):
        return p
    raise SystemExit(f"{name} not found: set PS4_LLVM_BIN to an LLVM bin folder (clang, ld.lld)")


def run(*cmd: str) -> None:
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"{' '.join(cmd)}\n{r.stdout}{r.stderr}")
    if r.stderr.strip():
        print(r.stderr.strip())


def flatten(elf_path: Path) -> bytes:
    with elf_path.open("rb") as f:
        elf = ELFFile(f)
        for sec in elf.iter_sections():
            if isinstance(sec, RelocationSection):
                for rel in sec.iter_relocations():
                    kind = RELOC_NAMES.get(rel["r_info_type"], str(rel["r_info_type"]))
                    if kind not in PC_RELATIVE:
                        raise SystemExit(f"{sec.name}: {kind} at {rel['r_offset']:#x} is not position independent "
                                         "(a global pointer or a pointer table?)")
        for name in (".data", ".bss"):
            sec = elf.get_section_by_name(name)
            if sec is not None and sec["sh_size"]:
                raise SystemExit(f"{name} is not empty ({sec['sh_size']} bytes): the agent cannot have globals")
        sym = elf.get_section_by_name(".symtab").get_symbol_by_name("agent_main")
        if not sym or sym[0]["st_value"] != 0:
            raise SystemExit("agent_main is not at offset 0")
        blob = bytearray()
        for name in (".text", ".rodata"):
            sec = elf.get_section_by_name(name)
            if sec is None or not sec["sh_size"]:
                continue
            addr = sec["sh_addr"]
            if addr < len(blob):
                raise SystemExit(f"{name} overlaps the previous section")
            blob += b"\0" * (addr - len(blob)) + sec.data()
        return bytes(blob)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    obj, elf = OUT / "agent.o", OUT / "agent.elf"
    run(tool("clang"), "--target=x86_64-pc-freebsd12-elf", "-std=c11", "-Os", "-ffreestanding", "-fno-builtin",
        "-fpie", "-fvisibility=hidden", "-fno-stack-protector", "-fno-asynchronous-unwind-tables", "-fno-jump-tables",
        "-mgeneral-regs-only", "-Wall", "-Wextra", "-Werror", "-c", str(HERE / "agent.c"), "-o", str(obj))
    run(tool("ld.lld"), "-m", "elf_x86_64_fbsd", "-static", "--emit-relocs", "--build-id=none",
        "-T", str(HERE / "agent.ld"), str(obj), "-o", str(elf))
    blob = flatten(elf)
    (OUT / "agent.bin").write_bytes(blob)
    version = next(line.split()[2] for line in (HERE / "agent_table.h").read_text(encoding="utf-8").splitlines()
                   if line.startswith("#define AGENT_VERSION"))
    b64 = base64.b64encode(blob).decode()
    lines = "\n".join(f'    "{b64[i:i + 100]}"' for i in range(0, len(b64), 100))
    BLOB_PY.write_text(
        '"""Generated by companion/build.py from companion/agent.c: do not edit."""\n\n'
        f"VERSION = {int(version)}\n"
        f'SHA256 = "{hashlib.sha256(blob).hexdigest()}"\n'
        f"BLOB_B64 = (\n{lines}\n)\n", newline="\n")
    print(f"agent v{version}: {len(blob)} bytes, sha256 {hashlib.sha256(blob).hexdigest()[:16]}...")
    print(f"wrote {BLOB_PY.relative_to(HERE.parent)} and {(OUT / 'agent.bin').relative_to(HERE.parent)}")


if __name__ == "__main__":
    sys.exit(main())
